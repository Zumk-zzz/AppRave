import type { ConfigContext, ExpoConfig } from 'expo/config';

/**
 * Настройки, которые зависят от окружения.
 *
 * Всё постоянное — имя, иконки, плагины — лежит в app.json; здесь только
 * то, что меняется от запуска к запуску. Expo сначала читает app.json,
 * а потом отдаёт его сюда, и мы дописываем адрес сервера.
 *
 * Зачем это нужно:
 *
 *  - при обычном запуске адрес выводится из адреса Metro: сервер на той
 *    же машине, и вписывать IP руками при каждой смене сети — мучение;
 *  - при работе через туннель так уже нельзя. Metro доступен по адресу
 *    вида xxx.exp.direct, а сервер по нему не отвечает: туннель ведёт
 *    только к сборщику. Адрес API приходится сообщать отдельно;
 *  - на боевом сервере он тоже задаётся снаружи, и это та же переменная.
 *    То есть туннель не «костыль на время разработки», а первый
 *    пользователь механизма, который понадобится при выкладке.
 */
export default ({ config }: ConfigContext): ExpoConfig => {
  const apiUrl = process.env.APPRAVE_API_URL?.trim();

  return {
    ...config,
    name: config.name ?? 'AppRave',
    slug: config.slug ?? 'apprave',
    extra: {
      ...config.extra,
      // Пусто — приложение само выведет адрес из адреса Metro
      apiUrl: apiUrl || undefined,
    },
  };
};
