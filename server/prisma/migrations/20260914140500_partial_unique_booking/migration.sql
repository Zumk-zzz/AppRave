-- Запрет двойной брони одного стола на одно событие.
--
-- Написано вручную, потому что Prisma не умеет WHERE в @@unique:
-- обычный уникальный индекс по (event_id, table_id) запретил бы и
-- повторную бронь после отмены, а это ровно то, что должно работать.
--
-- Живыми считаются только pending и paid. Отменённые и просроченные
-- брони в индекс не попадают, поэтому освободившийся стол можно
-- забронировать заново.
--
-- Гарантия на уровне базы, а не приложения: даже если два запроса
-- дойдут до вставки одновременно, второй получит ошибку уникальности.
CREATE UNIQUE INDEX "one_live_booking_per_table"
    ON "table_bookings" ("event_id", "table_id")
 WHERE "status" IN ('pending', 'paid');
