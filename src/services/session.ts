import type { User } from './types';

/**
 * Кто сейчас работает.
 *
 * Нужен мокам: в режиме сервера действующего сотрудника сервер узнаёт
 * из токена, а без сервера узнать его неоткуда — а журналу нужно имя
 * того, кто выдал напиток.
 *
 * Отдельный модуль без зависимостей, а не чтение из стора авторизации:
 * сервисы не должны зависеть от сторов, иначе получается кольцо —
 * стор читает сервис, сервис читает стор. Здесь же ровно то же, чем
 * для сетевого слоя служит сохранённый токен.
 */
let actor: User | null = null;

export function setActor(next: User | null): void {
  actor = next;
}

export function currentActor(): User | null {
  return actor;
}
